// Command go-licenses writes one combined notice file for the Go modules compiled into libbox.
// Input (stdin): lines "path\tversion\tdir\tmain" from `go list -deps`, possibly repeated.
// License detection uses the pinned github.com/google/licensecheck.
// Modules whose license cannot be identified are still listed, with a note, and reported
// on stderr as GitHub Actions warnings.
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/google/licensecheck"
)

type module struct{ path, version, dir string }

var licenseName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([.\-_].*)?$`)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go-licenses OUTPUT < modules.tsv")
		os.Exit(2)
	}
	mods := map[string]module{}
	sc := bufio.NewScanner(os.Stdin)
	for sc.Scan() {
		f := strings.Split(sc.Text(), "\t")
		if len(f) < 3 || f[0] == "" {
			continue
		}
		mods[f[0]] = module{f[0], f[1], f[2]}
	}
	if err := sc.Err(); err != nil {
		panic(err)
	}
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	var body strings.Builder
	undetected := 0
	licenses := map[string]int{}
	for _, p := range paths {
		m := mods[p]
		files := findLicenseFiles(m.dir)
		var names []string
		var texts []string
		for _, f := range files {
			data, err := os.ReadFile(filepath.Join(m.dir, f))
			if err != nil {
				panic(err)
			}
			cov := licensecheck.Scan(data)
			for _, match := range cov.Match {
				names = appendUnique(names, match.ID)
			}
			texts = append(texts, fmt.Sprintf("--- %s ---\n%s", f, strings.TrimRight(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n ")))
		}
		name := strings.Join(names, " AND ")
		if name == "" {
			undetected++
			if len(files) == 0 {
				name = "UNKNOWN (no license file found in the module)"
			} else {
				name = "UNKNOWN (license text not recognized; see the text below)"
			}
			fmt.Fprintf(os.Stderr, "::warning title=Go license not detected::%s %s: %s\n", m.path, m.version, name)
		}
		for _, n := range names {
			licenses[n]++
		}
		fmt.Fprintf(&body, "================================================================================\nModule:  %s\nVersion: %s\nLicense: %s\n================================================================================\n\n", m.path, m.version, name)
		if len(texts) == 0 {
			body.WriteString("NOTE: No license file was found for this module. See the module's upstream repository for its license terms.\n")
			if h := sourceHeader(m.dir); h != "" {
				body.WriteString("Source file header (" + h)
			}
			body.WriteString("\n")
		} else {
			if len(names) == 0 {
				body.WriteString("NOTE: The license could not be identified automatically; the full text is included as found.\n\n")
			}
			body.WriteString(strings.Join(texts, "\n\n") + "\n\n")
		}
	}
	ids := make([]string, 0, len(licenses))
	for id := range licenses {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	b.WriteString("Go modules compiled into Moth's native core (libbox: sing-box + Xray-core)\n")
	b.WriteString("Generated by scripts/go-licenses.sh. Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "Modules: %d\nLicense not detected: %d\nLicenses:", len(paths), undetected)
	for _, id := range ids {
		fmt.Fprintf(&b, " %s (%d)", id, licenses[id])
	}
	b.WriteString("\n\nContents:\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "  %s %s\n", p, mods[p].version)
	}
	b.WriteString("\n")
	b.WriteString(body.String())
	if err := os.WriteFile(os.Args[1], []byte(strings.TrimRight(b.String(), "\n")+"\n"), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "go-licenses: %d modules, %d licenses, %d undetected\n", len(paths), len(ids), undetected)
}

func findLicenseFiles(dir string) []string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		panic(err)
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && licenseName.MatchString(e.Name()) {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out
}

func appendUnique(s []string, v string) []string {
	for _, x := range s {
		if x == v {
			return s
		}
	}
	return append(s, v)
}

// sourceHeader returns the leading comment of the first Go file that mentions a license, as a hint.
func sourceHeader(dir string) string {
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	sort.Strings(files)
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		var lines []string
		for _, l := range strings.Split(string(data), "\n") {
			if !strings.HasPrefix(l, "//") {
				break
			}
			lines = append(lines, l)
		}
		h := strings.Join(lines, "\n")
		if strings.Contains(strings.ToLower(h), "license") {
			return filepath.Base(f) + "):\n" + h + "\n"
		}
	}
	return ""
}
